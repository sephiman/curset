"""Turn a lesson's question candidates (JSON) into its quiz exercise file, keys placed from the key text.

    python build_quiz.py CANDIDATES.json OUT.yaml [--verdicts VERDICTS.tsv]

Candidates: a list of {id, stem, key, distractors[3], explanation, citation, extract?, snippet?}.
A question whose id has a `fail` line in the verdict file is left out; the kept keys rotate through a, b, c, d in
a seeded order so positions stay balanced. Prints each stem with its keyed option and the length statistics.
"""

from __future__ import annotations

import argparse
import json
import random
import re
import statistics
import sys
from pathlib import Path

import yaml

SLOTS = ("a", "b", "c", "d")


def failed_ids(path: Path | None) -> set[str]:
    if path is None:
        return set()
    failed: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1] == "fail":
            failed.add(parts[0])
    return failed


def slot_order(count: int, seed: str) -> list[int]:
    order = [i % 4 for i in range(count)]
    random.Random(seed).shuffle(order)
    return order


def as_variant(candidate: dict[str, object], key_slot: int) -> dict[str, object]:
    distractors = list(candidate["distractors"])  # type: ignore[call-overload]
    if len(distractors) != 3:
        sys.exit(f"{candidate['id']}: needs exactly three distractors")
    texts = distractors[:key_slot] + [candidate["key"]] + distractors[key_slot:]
    options = []
    for slot, text in zip(SLOTS, texts, strict=True):
        option: dict[str, object] = {"id": slot}
        if text == candidate["key"]:
            option["correct"] = True
        option["text"] = {"en": text}
        options.append(option)
    variant: dict[str, object] = {
        "id": candidate["id"],
        "prompt": {"en": candidate["stem"]},
        "options": options,
        "explanation": {"en": candidate["explanation"]},
        "citation": candidate["citation"],
    }
    if candidate.get("extract"):
        variant["extract"] = {"en": candidate["extract"]}
    if candidate.get("snippet"):
        variant["snippet"] = candidate["snippet"]
    return variant


def report(variants: list[dict[str, object]]) -> None:
    longest, gaps = 0, []
    for variant in variants:
        options = variant["options"]  # type: ignore[assignment]
        lengths = [len(o["text"]["en"]) for o in options]  # type: ignore[index]
        key = next(len(o["text"]["en"]) for o in options if o.get("correct"))  # type: ignore[union-attr,index]
        longest += key == max(lengths)
        gaps.append(key - statistics.mean(x for x in lengths if x != key or lengths.count(key) > 1))
        stem = re.sub(r"\s+", " ", variant["prompt"]["en"])[:110]  # type: ignore[index]
        keyed = next(o for o in options if o.get("correct"))  # type: ignore[union-attr]
        print(f"{variant['id']} [{keyed['id']}] {stem} -> {keyed['text']['en'][:70]}")  # type: ignore[index]
    if variants:
        print(f"questions {len(variants)}; key longest {longest}/{len(variants)}; "
              f"mean key-minus-distractor chars {statistics.mean(gaps):+.1f}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("candidates", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--verdicts", type=Path)
    args = parser.parse_args()
    candidates = json.loads(args.candidates.read_text(encoding="utf-8"))
    failed = failed_ids(args.verdicts)
    kept = [c for c in candidates if c["id"] not in failed]
    slots = slot_order(len(kept), args.candidates.stem)
    variants = [as_variant(c, slot) for c, slot in zip(kept, slots, strict=True)]
    args.out.write_text(
        "# SPDX-License-Identifier: AGPL-3.0-only\n"
        f"# Generated by docs/backend-verification/s2/tools/build_quiz.py from {args.candidates.name}.\n"
        + yaml.safe_dump({"type": "quiz", "variants": variants}, allow_unicode=True, sort_keys=False, width=110),
        encoding="utf-8",
    )
    report(variants)
    print(f"kept {len(kept)}, dropped {len(candidates) - len(kept)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
