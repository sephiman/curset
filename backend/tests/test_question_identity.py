async def _sign_up(client: AsyncClient, username: str) -> None:
    body = {
        "username": username,
        "password": "correcthorse",
        "locale": "es",
        "courses": ["fixture-oposiciones"],
    }
    await client.post("/api/auth/register", json=body)
    await client.post("/api/auth/login", json={"username": username, "password": "correcthorse"})


async def _row(attempt_id: str) -> Attempt:
    async with get_sessionmaker()() as session:
        attempt = await session.get(Attempt, uuid.UUID(attempt_id))
        assert attempt is not None
        return attempt


async def _set(attempt_id: str, **values: object) -> None:
    async with get_sessionmaker()() as session:
        await session.execute(update(Attempt).where(Attempt.id == uuid.UUID(attempt_id)).values(**values))
        await session.commit()


def _correct_option(registry: CourseRegistry, exercise_id: str, variant_id: str) -> str:
    config = registry.exercise_configs[exercise_id][1]
    assert isinstance(config, QuizConfig)
    variant = next(v for v in config.variants if v.id == variant_id)
    return next(option.id for option in variant.options if option.correct)


async def test_an_attempt_follows_its_question_into_the_exercise_a_rebuild_moved_it_to(
    multi_client: AsyncClient,
) -> None:
    await _sign_up(multi_client, "mover")
    opened = (await multi_client.post(f"{OPOS}/exercises/m02-ex-1/attempts")).json()
    attempt = await _row(opened["attemptId"])
    assert attempt.variant_id is not None and attempt.variant_id.startswith("delegacion-")
    # Written when the question still sat in m02-ex-2; the rebuild has since moved it to m02-ex-1.
    await _set(opened["attemptId"], exercise_id="m02-ex-2")

    answer = {"optionId": _correct_option(_fixture(), "m02-ex-1", attempt.variant_id)}
    graded = await multi_client.post(f"{OPOS}/attempts/{opened['attemptId']}/answer", json={"answer": answer})
    assert graded.json()["correct"] is True

    review = (await multi_client.get(f"{OPOS}/attempts/{opened['attemptId']}")).json()
    assert review["exerciseId"] == "m02-ex-1" and review["prompt"] == opened["prompt"]
    here = (await multi_client.get(f"{OPOS}/attempts", params={"exercise_id": "m02-ex-1"})).json()
    there = (await multi_client.get(f"{OPOS}/attempts", params={"exercise_id": "m02-ex-2"})).json()
    assert [a["attemptId"] for a in here] == [opened["attemptId"]] and there == []

    stats = (await multi_client.get(f"{OPOS}/stats/me")).json()
    module = next(m for m in stats["modules"] if m["id"] == "m02")
    assert module["exercisesPassed"] == 1 and module["answered"] == 1


async def test_the_backfill_names_the_question_an_old_attempt_showed(multi_client: AsyncClient) -> None:
    await _sign_up(multi_client, "veteran")
    opened = [
        (await multi_client.post(f"{OPOS}/exercises/{e}/attempts")).json()["attemptId"]
        for e in ("m02-ex-1", "m01-ex-2", "m01-ex-3")
    ]
    moved, reworded, unknown = [await _row(attempt_id) for attempt_id in opened]
    # Rows from before attempts stored the question: one whose question a rebuild has since moved to
    # another exercise, one whose prompt was reworded after it was shown, one reworded beyond recognition.
    await _set(opened[0], variant_id=None, exercise_id="m02-ex-2")
    await _set(opened[1], variant_id=None, instance_snapshot={**reworded.instance_snapshot, "prompt": "Otro"})
    await _set(opened[2], variant_id=None, instance_snapshot={"prompt": "Otro", "payload": {"options": []}})

    registry = _fixture()
    async with get_sessionmaker()() as session:
        summary = await backfill_variant_ids(Catalog({registry.slug: registry}), session)
    counts = (summary.by_instance, summary.by_prompt, summary.by_options, summary.by_seed, summary.unresolved)
    assert counts == (1, 0, 1, 1, 0)
    assert (await _row(opened[0])).variant_id == moved.variant_id
    assert (await _row(opened[1])).variant_id == reworded.variant_id
    assert (await _row(opened[2])).variant_id == registry.drawn_variant_id("m01-ex-3", unknown.seed)

    async with get_sessionmaker()() as session:
        again = await backfill_variant_ids(Catalog({registry.slug: registry}), session)
    assert str(again) == str(type(again)())
