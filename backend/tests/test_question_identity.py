from tradeschool.exercises.quiz import QuizConfig
from tradeschool.exercises.types import ExerciseType

OPOS = "/api/courses/fixture-oposiciones"
UPDATE = os.environ.get("UPDATE_QUESTION_KEYS") == "1"
_SHOWN = {"kind", "prompt", "options", "answer", "items", "pairs"}

COURSES = [course for course in pipeline_courses() if course.excerpts is not None]


def _fixture() -> CourseRegistry:
    return next(course for course in pipeline_courses() if course.slug == "fixture-oposiciones")


def _solved(
    registry: CourseRegistry, configs: dict[str, tuple[ExerciseType, BaseModel]] | None = None
) -> list[SolvedQuestion]:
    return solved_questions(registry.manifest, configs or registry.exercise_configs, registry.languages[0])


def _keys(registry: CourseRegistry, configs: dict[str, tuple[ExerciseType, BaseModel]]) -> set[str]:
    return {question.key for question in _solved(registry, configs)}


def test_a_rebalanced_rebuild_keeps_the_key_of_every_question() -> None:
    registry = _fixture()
    moved = registry.exercise_configs["m02-ex-1"][1]
    target = registry.exercise_configs["m02-ex-2"][1]
    assert isinstance(moved, QuizConfig) and isinstance(target, QuizConfig)
    # A drop upstream: m02-ex-1's first question now opens m02-ex-2, as the bank build would regroup it.
    rebuilt = {
        **registry.exercise_configs,
        "m02-ex-1": (ExerciseType.QUIZ, QuizConfig(type="quiz", variants=moved.variants[1:])),
        "m02-ex-2": (
            ExerciseType.QUIZ,
            QuizConfig(type="quiz", variants=[moved.variants[0], *target.variants]),
        ),
    }
    assert _keys(registry, rebuilt) == _keys(registry, registry.exercise_configs)


def _shown(model: BaseModel) -> str:
    """What a learner sees of a question; the explanation and citation may be rewritten under the same key."""
    text = json.dumps(model.model_dump(mode="json", include=_SHOWN), ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def _rows(registry: CourseRegistry) -> list[tuple[str, str]]:
    shown: dict[str, str] = {}
    for _, _, exercise in registry.manifest.iter_exercises():
        config = registry.exercise_configs.get(exercise.id, (None, None))[1]
        if isinstance(config, QuizConfig):
            shown |= {question_key(v.id): _shown(v) for v in config.variants}
        elif isinstance(config, CaseConfig):
            shown |= {
                question_key(q.id, exercise.key): _shown(q.as_quiz().variants[0]) for q in config.questions
            }
    return [(question.key, shown[question.key]) for question in _solved(registry)]


def _report(rows: list[tuple[str, str]]) -> str:
    header = [
        "# question keys",
        "#",
        "# Generated by backend/tests/test_question_identity.py. A question's key is what its attempts,",
        "# reports, stats and excerpt hang off; a rebuild must never change it. Regenerate with",
        "# UPDATE_QUESTION_KEYS=1 after adding or rewording questions, never to accept a moved key.",
        "#",
        "# Tab-separated: key, digest of what the learner sees (prompt and options).",
    ]
    return "\n".join(header + [f"{key}\t{digest}" for key, digest in sorted(rows)]) + "\n"


def _frozen(text: str) -> list[tuple[str, str]]:
    return [
        (key, digest)
        for line in text.splitlines()
        if line and not line.startswith("#")
        for key, digest in [line.split("\t")]
    ]


@pytest.mark.parametrize("course", COURSES, ids=lambda c: c.slug)
def test_no_rebuild_changes_the_key_of_an_unchanged_question(course: CourseRegistry) -> None:
    golden = course_dir(course) / "question-keys.tsv"
    current = _rows(course)
    if UPDATE:
        golden.write_text(_report(current), encoding="utf-8")
    assert golden.exists(), f"no golden for {course.slug}: run with UPDATE_QUESTION_KEYS=1"
    now = {digest: key for key, digest in current}
    renamed = [
        f"{key} → {now[digest]}"
        for key, digest in _frozen(golden.read_text(encoding="utf-8"))
        if digest in now and now[digest] != key
    ]
    assert not renamed, "unchanged questions under a new key: " + ", ".join(renamed[:10])
    assert _report(current) == golden.read_text(encoding="utf-8"), f"{golden} moved — regenerate and review"


