"""S0 source coverage report (requirements 3.3): docs/backend-verification/s0/source-coverage.md from the judged
coverage TSVs, one row per programme bullet; a bullet with no judged row is listed as missing."""

from __future__ import annotations

import csv
import re
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
S0 = REPO / "docs" / "backend-verification" / "s0"
PROGRAMME = REPO / "content" / "backend-in-depth" / "programme.md"


def bullets() -> list[tuple[str, str, str]]:
    found = []
    for line in PROGRAMME.read_text(encoding="utf-8").split("\n"):
        if m := re.match(r"  - `([\d.a-z]+)` \[([FJ])\] (.*)$", line):
            found.append((m.group(1), m.group(2), m.group(3)))
    return found


def judged() -> dict[str, dict[str, str]]:
    rows: dict[str, dict[str, str]] = {}
    for tsv in sorted((S0 / "coverage").glob("m*.final.tsv")):
        with tsv.open(encoding="utf-8") as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                rows[row["bullet"]] = row
    return rows


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def main() -> None:
    rows = judged()
    classes: Counter[str] = Counter()
    lines = ["# Source coverage report — backend-in-depth (S0, 2026-11-13)", "",
             "Generated by `docs/backend-verification/s0/scripts/coverage_report.py` from the judged",
             "`coverage/mNN.final.tsv`. Classes: requirements section 4. Rules: R1 no Tier A, Tier B/C → J;",
             "R2 no acceptable source → dropped; R3 programme wording differs → the pinned documentation wins",
             "(`default-rules.tsv` logs each use). Tier B keys: `tier-b.yaml`; Tier C candidates not stored:",
             "`tier-c-candidates.yaml`.", "", "SUMMARY", "",
             "| Bullet | Mark | Class | Tier A anchors | Tier B/C | Rule | Pinned behaviour / note |",
             "|---|---|---|---|---|---|---|"]
    for bullet, mark, _text in bullets():
        row = rows.get(bullet)
        if row is None:
            classes["missing"] += 1
            lines.append(f"| `{bullet}` | {mark} | missing | | | | not judged |")
            continue
        classes[row["class"]] += 1
        note = "; ".join(x for x in (row.get("pinned", ""), row.get("note", "")) if x)
        lines.append(f"| `{bullet}` | {mark} | {row['class']} | {cell(row['tier_a'])} | {cell(row['tier_bc'])} "
                     f"| {row.get('rule', '')} | {cell(note)} |")
    summary = ", ".join(f"{k} {v}" for k, v in sorted(classes.items()))
    dropped = [b for b, _, _ in bullets() if rows.get(b, {}).get("class") == "drop"]
    text = "\n".join(lines).replace("SUMMARY", f"{len(bullets())} bullets: {summary}. Dropped: "
                                   f"{', '.join(dropped) or 'none'}.")
    (S0 / "source-coverage.md").write_text(text + "\n", encoding="utf-8")
    print(f"{len(bullets())} bullets: {summary}")


if __name__ == "__main__":
    main()
