"""build_check.py <lesson…>: each sentence of a rebuilt lesson is HEAD text or identical to a verified one.

Pool: the R2d expansion (`r2d/expansion/<lesson>.md`); a sentence counts when its latest verdict in the R2,
R2-tax and R2d reports is PASS. Writes `r2d/<lesson>/verify-build.md` (a PASS row per added sentence, with the
report its twin passed in) and prints the sentences that are neither HEAD text nor in the pool.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "docs/age-verification/aeat/r2d/tools"))

import r2dprov  # noqa: E402
from scripts.provenance import sentences  # noqa: E402

LESSONS = ROOT / "content/aeat-agentes-hacienda/es/lessons"
R2D = ROOT / "docs/age-verification/aeat/r2d"
EXPANSION = ROOT / "docs/_work/age-verification/aeat/r2d/expansion"
MARKER = re.compile(r"^(\d+\.?º?\)?|[a-zñ](?:\u00b4|')*\)|[A-Z]\)|\d+\\?\.)\s+")


def _pool() -> dict[str, tuple[str, str]]:
    """Verified sentence text → (sentence id, report where it passed)."""
    pool: dict[str, tuple[str, str]] = {}
    for path in sorted(EXPANSION.glob("m0*.md")):
        found = r2dprov.verdicts(path.stem)
        for sentence in sentences(path.read_text()):
            verdict, report = found.get(sentence.id, ("", ""))
            if verdict == "PASS":
                pool.setdefault(sentence.text, (sentence.id, report))
    # Text of a C1/C2 lesson was verified there; the provenance record marks it inherited.
    for course in ("age-administrativo-c1", "age-auxiliar-c2"):
        for path in sorted((ROOT / "content" / course / "es/lessons").glob("*.md")):
            for sentence in sentences(path.read_text()):
                pool.setdefault(sentence.text, (sentence.id, f"inherited: {course}/{path.stem}"))
    return pool


def _sid(text: str) -> str:
    return hashlib.sha1(text.encode()).hexdigest()[:10]


def _head(lesson: str) -> set[str]:
    path = f"content/aeat-agentes-hacienda/es/lessons/{lesson}.md"
    text = subprocess.run(["git", "show", f"HEAD:{path}"], cwd=ROOT, capture_output=True, text=True).stdout
    return {s.text for s in sentences(text)}


def _row_twin(row: str, pool: dict[str, tuple[str, str]]) -> tuple[str, str] | None:
    """An esquema row built from a verified list item: its main cell is the item's text, byte-identical."""
    cells = [c.strip() for c in row.strip().strip("|").split("|")]
    for cell in sorted(cells, key=len, reverse=True):
        for candidate in (cell, MARKER.sub("", cell, count=1)):
            for text, twin in pool.items():
                if text == candidate or MARKER.sub("", text, count=1) == candidate:
                    return twin
    # Nested sub-item: the splitter fuses it into its parent, so it is a verbatim part of a verified one.
    # Only the item's text (the longest cell) counts: a citation cell is a substring of many verified ones.
    candidate = MARKER.sub("", max(cells, key=len), count=1)
    if len(candidate) >= 15:
        for text, twin in pool.items():
            if candidate in text:
                return twin
    return None


def check(lesson: str, pool: dict[str, tuple[str, str]]) -> tuple[int, int, int, list[str]]:
    head = _head(lesson)
    head_pool = {text: (_sid(text), "HEAD") for text in head}
    base = added = derived = 0
    rows: list[str] = []
    missing: list[str] = []
    for sentence in sentences((LESSONS / f"{lesson}.md").read_text()):
        if sentence.text in head:
            base += 1
            continue
        twin = pool.get(sentence.text)
        note = "byte-identical"
        if twin is None and sentence.kind == "row":
            twin = _row_twin(sentence.text, pool)
            note = "esquema row whose cell is byte-identical to (or a verbatim sub-item of)"
        if twin is None and sentence.kind == "row":
            # A row built from an item of the pre-R2d lesson: that text keeps its HEAD provenance.
            twin = _row_twin(sentence.text, head_pool)
            note = "esquema row whose cell is byte-identical to (or a verbatim sub-item of) the HEAD sentence"
        if twin is None:
            missing.append(f"l.{sentence.first_line}: {sentence.text[:160]}")
            continue
        if sentence.id == twin[0]:
            added += 1
        else:
            derived += 1
        rows.append(
            f"| `{sentence.id}` | PASS | {note} `{twin[0]}` · {twin[1]} | "
            "built from the verified pool (script) | — |"
        )
    (R2D / lesson).mkdir(exist_ok=True)
    (R2D / lesson / "verify-build.md").write_text(
        f"# Build check — `{lesson}`\n\nGenerated by `r2d/tools/build_check.py`: every row is a sentence or "
        "esquema row added to the HEAD lesson, byte-identical to one that passed blind in the report "
        "named.\n\n"
        "| id | verdict | precept checked | note | replacement |\n|---|---|---|---|---|\n"
        + "\n".join(rows)
        + f"\n\nPASS {len(rows)} · FAIL 0\n"
    )
    return base, added, derived, missing


if __name__ == "__main__":
    verified = _pool()
    status = 0
    for name in sys.argv[1:]:
        base, added, derived, missing = check(name, verified)
        print(
            f"{name}: HEAD {base} · added byte-identical {added} · esquema rows from items {derived}"
            f" · not in pool {len(missing)}"
        )
        for line in missing:
            print("   ", line)
        status |= bool(missing)
    raise SystemExit(status)
