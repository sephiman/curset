"""Append a lesson's verified new questions to its published quiz exercise.

    python merge_questions.py LESSON

Reads docs/_work/backend-in-depth/d2/<lesson>.questions.json, leaves out every id with a fail line in
<lesson>.questions.verdicts.tsv, and appends the rest (keys rotated in a seeded order) to
content/backend-in-depth/exercises/<lesson>-ex-1.yaml; existing variants are untouched.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[4]
WORK = REPO / "docs" / "_work" / "backend-in-depth" / "d2"
spec = importlib.util.spec_from_file_location("build_quiz", REPO / "docs/backend-verification/s2/tools/build_quiz.py")
build_quiz = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
spec.loader.exec_module(build_quiz)  # type: ignore[union-attr]


def main() -> int:
    lesson = sys.argv[1]
    exercise = REPO / "content" / "backend-in-depth" / "exercises" / f"{lesson}-ex-1.yaml"
    candidates = json.loads((WORK / f"{lesson}.questions.json").read_text(encoding="utf-8"))
    failed = build_quiz.failed_ids(WORK / f"{lesson}.questions.verdicts.tsv")
    existing = yaml.safe_load(exercise.read_text(encoding="utf-8"))
    present = {v["id"] for v in existing["variants"]}
    kept = [c for c in candidates if c["id"] not in failed and c["id"] not in present]
    slots = build_quiz.slot_order(len(kept), f"{lesson}-d2")
    existing["variants"] += [build_quiz.as_variant(c, s) for c, s in zip(kept, slots, strict=True)]
    exercise.write_text(
        "# SPDX-License-Identifier: AGPL-3.0-only\n"
        f"# Generated by docs/backend-verification/s2/tools/build_quiz.py from {lesson}.questions.json;"
        " D2 additions appended by docs/backend-verification/d2/tools/merge_questions.py.\n"
        + yaml.safe_dump(existing, allow_unicode=True, sort_keys=False, width=110),
        encoding="utf-8",
    )
    print(f"{lesson}: {len(kept)} added, {len(candidates) - len(kept)} left out, {len(existing['variants'])} in the quiz")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
