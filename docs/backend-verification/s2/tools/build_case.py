"""Turn a case's scenario and verified question candidates into its case exercise file (requirements 6.4).

    python build_case.py MODULE_DIR CASE_ID OUT.yaml

Reads `<CASE_ID>.scenario.md` (first line `# Title`) and `<CASE_ID>.questions.json` (lesson questions plus a
`lesson` field); questions with a `fail` verdict in `<CASE_ID>.verdicts.tsv` are left out; keys placed from the
key text as in build_quiz. Exits non-zero when fewer than 10 questions remain (the loader's minimum).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml
from build_quiz import as_variant, failed_ids, report, slot_order

MINIMUM = 10


def main(argv: list[str]) -> int:
    folder, case_id, out = Path(argv[1]), argv[2], Path(argv[3])
    title, _, scenario = (folder / f"{case_id}.scenario.md").read_text(encoding="utf-8").partition("\n")
    candidates = json.loads((folder / f"{case_id}.questions.json").read_text(encoding="utf-8"))
    failed = failed_ids(folder / f"{case_id}.verdicts.tsv")
    kept = [c for c in candidates if c["id"] not in failed]
    print(f"{case_id}: kept {len(kept)}, dropped {len(candidates) - len(kept)}")
    if len(kept) < MINIMUM:
        print(f"{case_id}: under {MINIMUM} questions, not built")
        return 1
    questions = []
    for candidate, slot in zip(kept, slot_order(len(kept), case_id), strict=True):
        variant = as_variant(candidate, slot)
        variant.pop("extract", None)
        variant.pop("snippet", None)
        questions.append({"id": variant["id"], "lesson": candidate["lesson"], **{k: v for k, v in variant.items() if k != "id"}})
    report(questions)
    document = {
        "type": "case",
        "title": {"en": title.removeprefix("# ").strip()},
        "scenario": {"en": scenario.strip()},
        "questions": questions,
    }
    out.write_text(
        "# SPDX-License-Identifier: AGPL-3.0-only\n"
        f"# Generated by docs/backend-verification/s2/tools/build_case.py from {case_id}.questions.json.\n"
        + yaml.safe_dump(document, allow_unicode=True, sort_keys=False, width=110),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
